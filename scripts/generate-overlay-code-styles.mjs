// Generates src/lib/overlay/generated-code-styles.ts.
//
// Overlay code blocks are highlighted by shiki (github-light/github-dark) with inline
// hex colors and no per-token classes, so they can't be recolored by token type the
// clean way. This script reads shiki's github-light theme data and emits CSS that
// matches each token's hex and re-points it to the shared --ord-hljs-* theme tokens,
// so overlay code matches the other (highlight.js) renderers and follows the Theme
// Editor. Reading the theme here means the hex is never hand-copied and re-derives on
// a shiki version bump; only the scope->token table below is hand-maintained.
//
// Run with: npm run generate:overlay-styles (also runs automatically in prebuild).
import githubLight from '@shikijs/themes/github-light';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/lib/overlay/generated-code-styles.ts');

// The stable, hand-maintained semantic mapping: shiki/TextMate scope -> --ord-hljs-* token.
// Order is priority: the first token to claim a given color hex wins.
// Note github-light shares ONE color (#005cc5) across numbers, booleans/null (constant.*)
// AND JSON property names (support / meta.property-name); since the emitted colors are
// inline hex with no scope info they can't be split, so they all map to `number`. YAML
// mapping keys use a distinct color (entity.name.tag -> attr), which is what the overlay
// patch payloads (rendered as YAML) actually show.
const SCOPE_TOKEN = [
    { token: 'comment', scopes: ['comment'] },
    { token: 'string', scopes: ['string'] },
    { token: 'keyword', scopes: ['keyword', 'storage', 'storage.type'] },
    { token: 'attr', scopes: ['entity.name.tag'] },
    { token: 'number', scopes: ['constant', 'support', 'meta.property-name'] },
    { token: 'function', scopes: ['entity.name', 'entity'] },
];

function scopeElements(scope) {
    const list = Array.isArray(scope) ? scope : [scope];
    return list
        .flatMap((s) => String(s).split(','))
        .map((s) => s.trim())
        .filter(Boolean);
}

function foregroundFor(scope) {
    for (const tc of githubLight.tokenColors ?? []) {
        const fg = tc.settings?.foreground;
        if (fg && scopeElements(tc.scope).includes(scope)) return fg.toLowerCase();
    }
    return null;
}

// token -> hex (first matching scope wins)
const tokenHex = new Map();
for (const { token, scopes } of SCOPE_TOKEN) {
    for (const scope of scopes) {
        const hex = foregroundFor(scope);
        if (hex) {
            tokenHex.set(token, hex);
            break;
        }
    }
}

// hex -> token (first token in SCOPE_TOKEN order claims each hex)
const hexToken = new Map();
for (const { token } of SCOPE_TOKEN) {
    const hex = tokenHex.get(token);
    if (hex && !hexToken.has(hex)) hexToken.set(hex, token);
}

const defaultFg = (githubLight.fg || githubLight.colors?.['editor.foreground'] || '#24292e').toLowerCase();

// Selectors are scoped `.overlay-root.ord-ui .ord-code-block .shiki ...` (specificity
// 0,5,1) to beat the ui-components dark rule (0,4,1). The `i` flag is required because
// shiki emits token hex in UPPERCASE but the pre base color in lowercase. `!important`
// is required to override shiki's inline styles. The light hex is always present in the
// dual-theme output, and --ord-hljs-* resolves per-mode at .overlay-root(.dark).ord-ui.
const SCOPE = '.overlay-root.ord-ui .ord-code-block .shiki';
const tokenRules = [...hexToken.entries()].map(
    ([hex, token]) => `${SCOPE} span[style*="color:${hex}" i] { color: var(--ord-hljs-${token}) !important; }`,
);
const baseRule =
    `${SCOPE},\n${SCOPE} span[style*="color:${defaultFg}" i] ` +
    `{ color: var(--ord-code-fg, var(--ord-hljs-punctuation)) !important; }`;

const css = [...tokenRules, baseRule].join('\n');

const banner = `// AUTO-GENERATED by scripts/generate-overlay-code-styles.mjs — do not edit.
// Regenerate with: npm run generate:overlay-styles
//
// Maps shiki github-light token colors to the shared --ord-hljs-* theme tokens so overlay
// code blocks match the other renderers and follow the Theme Editor (light + dark).
// Derived from @shikijs/themes "${githubLight.name ?? 'github-light'}".`;

writeFileSync(OUT, `${banner}\nexport default \`\n${css}\n\`;\n`, 'utf8');
// eslint-disable-next-line no-console -- build-time script progress output is intentional.
console.log(`Wrote ${OUT} (${hexToken.size} token rules + base rule)`);
